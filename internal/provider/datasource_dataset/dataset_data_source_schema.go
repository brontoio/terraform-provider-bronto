package datasource_dataset

import (
	"context"

	"github.com/hashicorp/terraform-plugin-framework/datasource/schema"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

func DatasetDataSourceSchema(ctx context.Context) schema.Schema {
	identityAttributes := map[string]schema.Attribute{
		"type": schema.StringAttribute{
			Computed:            true,
			Description:         "The type of actor: API_KEY_ID or USER_ID.",
			MarkdownDescription: "The type of actor: `API_KEY_ID` or `USER_ID`.",
		},
		"id": schema.StringAttribute{
			Computed:            true,
			Description:         "The identifier of the actor (user id or API key id).",
			MarkdownDescription: "The identifier of the actor (user id or API key id).",
		},
	}

	return schema.Schema{
		Description:         "Looks up a Bronto dataset by ID, or by its collection and dataset name.",
		MarkdownDescription: "Looks up a Bronto dataset by ID, or by its collection and dataset name.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Optional:            true,
				Computed:            true,
				Description:         "The unique identifier of the dataset. Exactly one of id, or collection and dataset together, must be set.",
				MarkdownDescription: "The unique identifier of the dataset. Exactly one of `id`, or `collection` and `dataset` together, must be set.",
			},
			"collection": schema.StringAttribute{
				Optional:            true,
				Computed:            true,
				Description:         "The name of the log collection. Must be set together with dataset.",
				MarkdownDescription: "The name of the log collection. Must be set together with `dataset`.",
			},
			"dataset": schema.StringAttribute{
				Optional:            true,
				Computed:            true,
				Description:         "The name of the dataset within the collection. Must be set together with collection.",
				MarkdownDescription: "The name of the dataset within the collection. Must be set together with `collection`.",
			},
			"is_system_generated": schema.BoolAttribute{
				Computed:            true,
				Description:         "Whether the dataset is generated by the system.",
				MarkdownDescription: "Whether the dataset is generated by the system.",
			},
			"tags": schema.MapAttribute{
				ElementType:         types.StringType,
				Computed:            true,
				Description:         "A map of key value pairs associated with the dataset.",
				MarkdownDescription: "A map of key value pairs associated with the dataset.",
			},
			"parser_id": schema.StringAttribute{
				Computed:            true,
				Description:         "Identifier of the parser used to process incoming events for this dataset.",
				MarkdownDescription: "Identifier of the parser used to process incoming events for this dataset.",
			},
			"parser_matching_exempt": schema.BoolAttribute{
				Computed:            true,
				Description:         "Whether this dataset is exempt from automatic parser matching.",
				MarkdownDescription: "Whether this dataset is exempt from automatic parser matching.",
			},
			"metadata": schema.SingleNestedAttribute{
				Computed:            true,
				Description:         "Common metadata about the dataset.",
				MarkdownDescription: "Common metadata about the dataset.",
				Attributes: map[string]schema.Attribute{
					"created_at": schema.Int64Attribute{
						Computed:            true,
						Description:         "Creation timestamp in milliseconds since epoch.",
						MarkdownDescription: "Creation timestamp in milliseconds since epoch.",
					},
					"created_by": schema.SingleNestedAttribute{
						Computed:            true,
						Description:         "The actor who created the dataset.",
						MarkdownDescription: "The actor who created the dataset.",
						Attributes:          identityAttributes,
					},
					"modified_at": schema.Int64Attribute{
						Computed:            true,
						Description:         "Last update timestamp in milliseconds since epoch.",
						MarkdownDescription: "Last update timestamp in milliseconds since epoch.",
					},
					"modified_by": schema.SingleNestedAttribute{
						Computed:            true,
						Description:         "The actor who last updated the dataset.",
						MarkdownDescription: "The actor who last updated the dataset.",
						Attributes:          identityAttributes,
					},
					"deleted_at": schema.Int64Attribute{
						Computed:            true,
						Description:         "Deletion timestamp in milliseconds since epoch.",
						MarkdownDescription: "Deletion timestamp in milliseconds since epoch.",
					},
					"deleted_by": schema.SingleNestedAttribute{
						Computed:            true,
						Description:         "The actor who deleted the dataset.",
						MarkdownDescription: "The actor who deleted the dataset.",
						Attributes:          identityAttributes,
					},
				},
			},
		},
	}
}

type IdentityModel struct {
	Type types.String `tfsdk:"type"`
	Id   types.String `tfsdk:"id"`
}

type MetadataModel struct {
	CreatedAt  types.Int64    `tfsdk:"created_at"`
	CreatedBy  *IdentityModel `tfsdk:"created_by"`
	ModifiedAt types.Int64    `tfsdk:"modified_at"`
	ModifiedBy *IdentityModel `tfsdk:"modified_by"`
	DeletedAt  types.Int64    `tfsdk:"deleted_at"`
	DeletedBy  *IdentityModel `tfsdk:"deleted_by"`
}

type DatasetModel struct {
	Id                   types.String   `tfsdk:"id"`
	Collection           types.String   `tfsdk:"collection"`
	Dataset              types.String   `tfsdk:"dataset"`
	IsSystemGenerated    types.Bool     `tfsdk:"is_system_generated"`
	Tags                 types.Map      `tfsdk:"tags"`
	ParserId             types.String   `tfsdk:"parser_id"`
	ParserMatchingExempt types.Bool     `tfsdk:"parser_matching_exempt"`
	Metadata             *MetadataModel `tfsdk:"metadata"`
}
